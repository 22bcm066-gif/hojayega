const t = (daysFromNow, hh = '18:00') => {
  const d = new Date()
  d.setDate(d.getDate() + daysFromNow)
  return { date: d.toISOString().slice(0, 10), time: hh }
}

const ago = (hoursAgo) => {
  const d = new Date()
  d.setHours(d.getHours() - hoursAgo)
  return d.toISOString()
}

